"""Interactive processes — pexpect, for the class of commands bash cannot run.

The bash tool pipes stdin from nowhere, so anything that asks a question
mid-run (ssh host-key confirmation, a sudo password, fdisk, an installer, a
REPL) blocks until the timeout kills it. This tool spawns the program on a
pseudo-terminal and answers its prompts from a script the model supplies up
front, which keeps it one tool instead of a stateful spawn/send/expect trio.

A step's answer can come from two places: `send` (a literal string, the
model writes it directly) or `send_env` (the NAME of an environment
variable — `os.environ` is read for the actual value locally, in this
process, never by the model). `send_env` exists for exactly one reason: a
literal `send` means the actual secret has to be generated by the model to
appear in the tool call at all — round-tripping it through the model's own
context and Anthropic's API twice (once in, once out) even though
`secret: true` keeps it out of the RETURNED transcript afterward. Naming an
env var instead means the model only ever sees/writes a NAME, and the real
value is resolved by this module's own Python code, on this machine, never
touching a prompt or a completion. Same `token_env`/`api_key_env`-name-not-
value pattern this project's own `config.toml` already uses everywhere else
for secrets, applied here to interactive credential prompts specifically.
Always treated as secret for transcript purposes regardless of the `secret`
field — there is no scenario where naming an env var and then printing its
resolved value back into a transcript the model reads makes sense.

Deliberately no file-based equivalent (`send_file`, briefly added and then
removed the same session) — a literal env var, freshly `export`ed into an
interactive shell, requires no new persistent artifact at all; a file-based
version requires the secret to be written to disk in plain text as a matter
of normal use, which is a strictly worse default. An env var is not immune
to ending up on disk either (shell history if typed interactively and not
suppressed, or a startup file if `export`ed there for persistence) — this
tool cannot enforce how the caller manages the variable it names — but it
does not REQUIRE a new plaintext file to exist the way a file-based option
would.

A third source, `send_secret`, closes that remaining gap for real: the NAME
of a `pass` (the standard unix password manager, passwordstore.org) entry —
resolved locally via `pass show <name>`, whose real value is genuinely
encrypted at rest (GPG), not plaintext-if-you're-careful the way `send_env`
is. `pass`/`gnupg`/`pinentry-curses` need no GUI, no D-Bus session, no
desktop environment of any kind — confirmed to work identically on a
graphical desktop or a bare SSH-only server, and available (directly or via
EPEL) on Ubuntu/Debian/Fedora/Arch/RHEL/CentOS/Oracle Linux 8+ (RHEL-family
7 is the one real gap — `pass` was dropped from EPEL7 in 2019). Rejected
`secret-tool`/libsecret for this same purpose: it requires a D-Bus Secret
Service daemon tied to a logged-in graphical session (GNOME Keyring, KDE's
ksecretd — confirmed both can be running simultaneously on the SAME machine,
live, on this one), which simply doesn't exist on a headless server at all —
not a "which desktop environment" gap, a "no desktop environment" gap.
`pass` has no such requirement.

Requires:  pip install pexpect
"""

