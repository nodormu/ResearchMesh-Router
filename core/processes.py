_TOOL_NAMES = {t["name"] for t in TOOLS}
_MAX_TRANSCRIPT = 12000
_DEFAULT_TIMEOUT = 30
# How long `send_secret`'s `pass show` subprocess gets before giving up —
# see `_resolve_reply`'s own docstring for why this exists at all (an
# unanswerable pinentry prompt with no terminal here would otherwise hang
# for the full interactive_run timeout). A plain module attribute, not a
# function default, specifically so test_processes.py can shrink it instead
# of a real test run actually waiting out the production value.
_SEND_SECRET_TIMEOUT = 10

# Entry names that have already been explicitly presented AND re-referenced
# once, for the life of this process — see `_resolve_reply`'s own docstring
# for the incident this closes: a real live session skipped straight to
# `"send_secret": "sudo_admin"` on the FIRST attempt, without ever showing
# the "please select the cred name I need to use:" prompt first, because
# nothing forced it to — the "?" sentinel only helps if the caller chooses
# to use it, and this one didn't, even though "sudo_admin" was the only
# entry that existed. A module-level set, not a function default, because
# it has to persist across separate `_run()` calls within the same running
# process to mean anything.
_confirmed_secret_entries: set[str] = set()


def handles(name: str) -> bool:
    return name in _TOOL_NAMES


async def execute(name: str, tool_input: dict) -> str:
    if name != "interactive_run":
        return json.dumps({"error": f"unknown process tool {name!r}"})
    return await asyncio.to_thread(_run, tool_input)


def _resolve_reply(step: dict) -> tuple[str, bool, str | None]:
    """Return (reply_text, is_secret, error) for one step.

    Exactly one of `send`/`send_env`/`send_secret` must be present —
    anything else (zero, or more than one) is a caller error, returned as
    `error` rather than silently guessing which one was meant. `send_env`/
    `send_secret` always come back with `is_secret=True`; a literal `send`
    respects the step's own `secret` field (default `False`), matching this
    tool's existing behavior for that case unchanged.

    `send_secret` shells out to `pass show <name>` with a 10-second timeout,
    not an unbounded wait — if `pass`/`gpg` end up needing a passphrase
    prompt (the GPG key isn't already unlocked in `gpg-agent`'s cache) there
    is no terminal here for `pinentry` to use, so this would otherwise hang
    for the full `interactive_run` timeout on top of whatever the REAL
    command's own steps needed, indistinguishable from a genuine hang. The
    error message says so explicitly rather than just "timed out" — unlock
    the key once, manually, in a real terminal first, which caches it in
    `gpg-agent` for a while and lets subsequent calls succeed silently.
    """
    sources = [k for k in ("send", "send_env", "send_secret") if k in step]
    if len(sources) == 0:
        return "", False, "must include one of `send`, `send_env`, `send_secret`"
    if len(sources) > 1:
        return "", False, f"only one of `send`/`send_env`/`send_secret` allowed, got {sources}"

    if "send" in step:
        return str(step["send"]), bool(step.get("secret")), None

    if "send_env" in step:
        var_name = str(step["send_env"])
        value = os.environ.get(var_name)
        if value is None:
            return "", False, f"environment variable {var_name!r} is not set"
        return value, True, None

    entry_name = str(step["send_secret"])
    if entry_name == "?" or entry_name not in _confirmed_secret_entries:
        # First reference to this exact name (or an explicit "?") — refuse
        # to use it yet, REGARDLESS of whether it's real, correct, or the
        # only entry that exists. Recording it here means the NEXT call
        # that names this same entry is treated as the confirmed one — so
        # a real task still only takes two calls total (present, then use),
        # not a repeated prompt every single time the same entry comes up
        # later in the same session.
        _confirmed_secret_entries.add(entry_name)
        return "", False, _select_entry_prompt()

    try:
        result = subprocess.run(
            ["pass", "show", entry_name],
            capture_output=True,
            text=True,
            timeout=_SEND_SECRET_TIMEOUT,
            check=False,
        )
    except FileNotFoundError:
        return "", False, "`pass` is not installed (see the module docstring for setup)"
    except subprocess.TimeoutExpired:
        return "", False, (
            f"`pass show {entry_name!r}` did not return within "
            f"{_SEND_SECRET_TIMEOUT}s — likely waiting on a GPG passphrase "
            "prompt with no terminal here to answer it. Unlock the key "
            "once, manually, in your own terminal (`pass show ...` there) "
            "first — gpg-agent caches it for a while afterward, and this "
            "call will then succeed silently."
        )
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip() or "unknown error"
        return "", False, f"`pass show {entry_name!r}` failed: {detail}{_available_entries_hint()}"
    first_line = result.stdout.splitlines()[0] if result.stdout else ""
    return first_line, True, None


def _select_entry_prompt() -> str:
    """The exact, hardcoded text returned when a step uses `"send_secret": "?"`
    — the caller's explicit way of saying "I need a credential here but don't
    know which vault entry to use." Builds a fixed-format message from the
    REAL entries in the vault; nothing about the wording is left to whatever
    composes the final reply to the user. That's the whole point: which
    entries actually exist, and how the request for one is phrased, are both
    decided here, in code, not by a model that might wrap it in an
    explanation, phrase it as a vague hypothetical, or ask as an open-ended
    question — no version of that was reliable in practice, confirmed live,
    more than once, on real interactive_run credential prompts.

    Reads `$PASSWORD_STORE_DIR` (falling back to `~/.password-store`, `pass`'s
    own documented default) and walks it directly for `*.gpg` files, rather
    than parsing `pass ls`'s own tree-drawing output — found live, while
    building this, that naively stripping `pass ls`'s box-drawing characters
    loses FOLDER STRUCTURE for a nested entry (`aws/prod` rendered under an
    `aws` branch came out as bare `prod`, which is not a valid `pass show`
    argument on its own). Walking the real files gives the exact, full
    relative path for every entry, unambiguously, matching what `pass show`
    actually needs. No decryption happens here — `.gpg` filenames are read
    directly off the filesystem, never opened.
    """
    store_dir = Path(os.environ.get("PASSWORD_STORE_DIR", "~/.password-store")).expanduser()
    if not store_dir.is_dir():
        return f"no password store found at {store_dir} — nothing to select"
    entries = sorted(
        str(p.relative_to(store_dir))[: -len(".gpg")]
        for p in store_dir.rglob("*.gpg")
    )
    if not entries:
        return "the password store is empty — nothing to select"
    return "please select the cred name I need to use:\n" + "\n".join(entries)


def _available_entries_hint() -> str:
    """Appended to a `send_secret` failure message: the real list of entry
    NAMES currently in the vault (never their values — `pass ls` is a pure
    directory listing, confirmed live it needs no passphrase and touches no
    encrypted content at all). Exists specifically so a wrong or made-up
    entry name doesn't just fail blind — the caller sees what's actually
    there immediately, in the same error, rather than needing a separate
    round trip to ask "what do you even have?" This is a safety net, not a
    substitute for the actual rule: never pick which entry to use by
    guessing among what's listed here — a human names the exact entry for
    every real task, every time. Best-effort — if `pass ls` itself fails for
    any reason, the base error above is still returned on its own.
    """
    try:
        result = subprocess.run(
            ["pass", "ls"],
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
    except Exception:
        return ""
    if result.returncode != 0 or not result.stdout.strip():
        return ""
    return f"\n\nEntries actually in the vault:\n{result.stdout.strip()}"


def _redact(transcript: str, secret_values: list[str]) -> str:
    """Replace every occurrence of every value in `secret_values` anywhere
    in `transcript` with `***` — not just the one line where a step
    actually sent it.

    This is the fix for a real, live-caught bug, not a defensive-only
    measure: the previous design only ever substituted "***" at the exact
    call site that SENT a secret reply, which correctly hid it from that one
    line but did nothing about the child process printing the same value
    back out on its OWN, later, as unrelated output (confirmed live: a
    prompt/echo test script — `read -s -p ...; echo "GOT:[$val]"` — put a
    real `pass`-sourced secret in plain text into the returned transcript,
    on the `echo` line, which this function's call site never touched
    before). Scrubbing the complete, final transcript for every known
    secret value, wherever it appears, closes that gap regardless of why or
    how the value ended up repeated. Empty values are skipped — replacing
    "" would insert `***` between every character.
    """
    for value in set(secret_values):
        if value:
            transcript = transcript.replace(value, "***")
    return transcript


def _run(tool_input: dict) -> str:
    try:
        import pexpect
    except ImportError:
        return json.dumps(
            {
                "error": "pexpect is not installed — `pip install pexpect` to "
                "enable the interactive_run tool"
            }
        )

    command = tool_input.get("command", "")
    if not command.strip():
        return json.dumps({"error": "no command provided"})

    steps = tool_input.get("steps") or []
    timeout = int(tool_input.get("timeout") or _DEFAULT_TIMEOUT)

    # Resolve every step's actual reply text AND whether it counts as secret
    # up front, before spawning anything — a missing env var or unreadable
    # file is a configuration error the caller should see immediately, not
    # something that surfaces only after a real program has already been
    # left mid-prompt (ssh half-connected, an installer half-run) by a step
    # further down the list.
    resolved_replies: list[tuple[str, bool]] = []
    for i, step in enumerate(steps):
        reply, is_secret, error = _resolve_reply(step)
        if error:
            return json.dumps({"error": f"step {i}: {error}"})
        resolved_replies.append((reply, is_secret))

    transcript: list[str] = []
    matched = 0
    timed_out_at = None

    try:
        child = pexpect.spawn(
            SHELL_EXECUTABLE,
            ["-c", apply_shell_prelude(command)],
            encoding="utf-8",
            codec_errors="replace",
            timeout=timeout,
            echo=False,
        )
    except Exception as e:
        return json.dumps({"error": f"could not spawn command: {e}"})

    try:
        for step, (reply, is_secret) in zip(steps, resolved_replies, strict=True):
            pattern = str(step.get("expect", ""))
            try:
                child.expect(pattern)
            except pexpect.TIMEOUT:
                timed_out_at = pattern
                break
            except pexpect.EOF:
                timed_out_at = None
                transcript.append(child.before or "")
                break

            transcript.append((child.before or "") + (child.after or ""))
            child.sendline(reply)
            # Appended here as the real value, unconditionally -- NOT "***"
            # even when `is_secret` is true. Redaction happens exactly once,
            # at the very end, via `_redact()` over the COMPLETE transcript
            # (see that function's own docstring for why appending "***"
            # only at this one call site was the actual bug: it missed the
            # secret entirely if the child process later echoed it back on
            # its own, in unrelated output this code never touches here).
            transcript.append(reply + "\n")
            matched += 1

        # Drain whatever the program prints after the last answer.
        try:
            child.expect(pexpect.EOF)
            transcript.append(child.before or "")
        except pexpect.TIMEOUT:
            transcript.append(child.before or "")
            if timed_out_at is None:
                timed_out_at = "(waiting for the program to exit)"
    finally:
        try:
            child.close(force=True)
        except (OSError, pexpect.ExceptionPexpect) as e:
            print(f"[processes] child.close failed (ignored): {e}")

    full_transcript = _redact(
        "".join(transcript),
        secret_values=[reply for reply, is_secret in resolved_replies if is_secret],
    )

    return json.dumps(
        {
            "transcript": clip(full_transcript, _MAX_TRANSCRIPT),
            "steps_matched": matched,
            "steps_total": len(steps),
            "exit_status": child.exitstatus,
            "signal_status": child.signalstatus,
            "timed_out_waiting_for": timed_out_at,
        }
    )
